package main

import "testing"

// The reported failure: run an arena with both ONNX endpoints closed and it
// exits cleanly with a normal-looking onnx vs onnx2 result. Both backends
// answer with the heuristic rather than failing, so every game completes and
// nothing in the report says the model never ran. A promotion gate would score
// the heuristic against itself and call it a candidate evaluation.
func TestArenaRefusesResultDecidedByFallback(t *testing.T) {
	cfg := MatchConfig{BlackEval: "onnx", WhiteEval: "onnx2"}

	// Every evaluation fell back: the endpoints were closed.
	allFallback := MatchResult{Games: 40, EvalRequests: 5000, EvalFallbacks: 5000, EvalFallbackRate: 1.0}
	if err := checkEvalHealth(cfg, allFallback); err == nil {
		t.Fatal("accepted a result where 100% of evaluations were the heuristic")
	}

	// The subtler case: the backend never ran at all, so there is nothing to
	// take a rate over and a naive rate check reads 0.0 as healthy.
	neverRan := MatchResult{Games: 40}
	if err := checkEvalHealth(cfg, neverRan); err == nil {
		t.Fatal("accepted a result where no model evaluation was attempted")
	}

	// A handful of timeouts across a long gate is noise, not a broken model.
	occasional := MatchResult{Games: 600, EvalRequests: 100000, EvalFallbacks: 500, EvalFallbackRate: 0.005}
	if err := checkEvalHealth(cfg, occasional); err != nil {
		t.Errorf("rejected a healthy run over 0.5%% fallbacks: %v", err)
	}
}

// A heuristic-only arena has no model to fall back from, so the check must not
// fire: the reproducible strength baseline is exactly this shape.
func TestEvalHealthIgnoresHeuristicOnlyArenas(t *testing.T) {
	cfg := MatchConfig{BlackEval: "heuristic", WhiteEval: "heuristic"}
	if err := checkEvalHealth(cfg, MatchResult{Games: 200}); err != nil {
		t.Errorf("heuristic-only arena rejected: %v", err)
	}
}

func TestNamesONNX(t *testing.T) {
	for _, name := range []string{"onnx", "onnx2", "onnx-batch", "ONNX"} {
		if !namesONNX(name) {
			t.Errorf("namesONNX(%q) = false", name)
		}
	}
	for _, name := range []string{"heuristic", "uniform", "batched", "mock-batch", ""} {
		if namesONNX(name) {
			t.Errorf("namesONNX(%q) = true", name)
		}
	}
}

// The counters are process-wide, so a second match must not inherit the first
// one's fallbacks. RunMatch resets them; this pins that contract.
func TestEvalHealthResets(t *testing.T) {
	resetEvalHealth()
	recordEvalRequests(100)
	recordEvalFallbacks(40)
	rate, req, fb := evalFallbackRate()
	if rate != 0.4 || req != 100 || fb != 40 {
		t.Fatalf("got rate=%v requests=%d fallbacks=%d, want 0.4/100/40", rate, req, fb)
	}
	resetEvalHealth()
	if rate, req, fb := evalFallbackRate(); rate != 0 || req != 0 || fb != 0 {
		t.Errorf("after reset got rate=%v requests=%d fallbacks=%d", rate, req, fb)
	}
}

// Self-play is the worse case of the two. A gate decided by the fallback is one
// wrong promotion; a SHARD generated by the fallback is training data labelled
// with a champion that never played it, and it stays in the replay window for
// as many cycles as the window is deep.
func TestSelfplayRefusesShardsTheModelDidNotGenerate(t *testing.T) {
	onnx := SelfplayConfig{EvalMode: "onnx"}
	if err := checkSelfplayEvalHealth(onnx, 1.0, 5000, 5000); err == nil {
		t.Error("accepted a shard where every evaluation was the heuristic")
	}
	if err := checkSelfplayEvalHealth(onnx, 0, 0, 0); err == nil {
		t.Error("accepted a shard where the model never ran at all")
	}
	if err := checkSelfplayEvalHealth(onnx, 0.005, 100000, 500); err != nil {
		t.Errorf("rejected a healthy run over 0.5%% fallbacks: %v", err)
	}
}

// Mix mode deliberately plays part of its games with the heuristic, but those
// games never reach the batched evaluator, so they are not counted as requests
// and must not read as failures. A mix run whose MODEL half died still must.
func TestSelfplayMixIsJudgedOnItsModelHalf(t *testing.T) {
	mix := SelfplayConfig{EvalMode: "mix", ONNXFraction: 0.7}
	if err := checkSelfplayEvalHealth(mix, 0.004, 70000, 280); err != nil {
		t.Errorf("healthy mix run rejected: %v", err)
	}
	if err := checkSelfplayEvalHealth(mix, 1.0, 70000, 70000); err == nil {
		t.Error("mix run whose model half fell back entirely was accepted")
	}
	if err := checkSelfplayEvalHealth(mix, 0, 0, 0); err == nil {
		t.Error("mix run where the model never ran was accepted")
	}
}

// A heuristic-only self-play run has no model to fall back from. Cycle 1 of
// every training run is exactly this and must not be blocked.
func TestSelfplayHeuristicOnlyIsNotChecked(t *testing.T) {
	if err := checkSelfplayEvalHealth(SelfplayConfig{EvalMode: "heuristic"}, 0, 0, 0); err != nil {
		t.Errorf("heuristic bootstrap rejected: %v", err)
	}
}

// sampleWithPass builds one row whose policy puts `pass` mass on the pass entry
// and spreads the rest evenly over the board.
func sampleWithPass(moveNum int, fullSearch bool, pass float32) Sample {
	const pol = 9*9 + 1
	p := make([]float32, pol)
	rest := (1 - pass) / float32(pol-1)
	for i := range p[:pol-1] {
		p[i] = rest
	}
	p[pol-1] = pass
	return Sample{MoveNum: moveNum, FullSearch: fullSearch, Policy: p}
}

func shardWith(pass float32) []Sample {
	out := make([]Sample, 0, 40)
	for i := 0; i < 40; i++ {
		out = append(out, sampleWithPass(i%passShareOpeningPlies, true, pass))
	}
	return out
}

// The numbers are the ones measured on the live run this check came out of:
// heuristic-generated shards at 0.007, net-generated shards whose networks were
// losing strength at up to 0.087. The check has to separate those two when it is
// switched on, and stay out of the way when it is not.
func TestSelfplayPassCollapseSeparatesMeasuredShards(t *testing.T) {
	healthy, rows := openingPassShare(shardWith(0.007))
	if rows != 40 {
		t.Fatalf("counted %d opening rows, want 40", rows)
	}
	collapsed, _ := openingPassShare(shardWith(0.087))

	// A bar between the two observed bands admits one and refuses the other.
	const bar = 0.05
	if err := checkSelfplayPassCollapse(healthy, rows, bar); err != nil {
		t.Errorf("refused a heuristic-level shard at %.3f: %v", healthy, err)
	}
	if err := checkSelfplayPassCollapse(collapsed, rows, bar); err == nil {
		t.Errorf("accepted a collapsed shard at %.3f", collapsed)
	}
}

// Default is measure-and-record. The first version of this check shipped a
// constant 0.12 bar, which sat above every collapsed shard actually observed
// (worst: 0.087) and so could never fire -- a check that cannot fail is not a
// check. Until a run exists that produces healthy net self-play there is no
// upper end of the healthy band to calibrate against, so the refusal is opt-in.
func TestSelfplayPassCollapseIsOptIn(t *testing.T) {
	share, rows := openingPassShare(shardWith(0.9))
	if err := checkSelfplayPassCollapse(share, rows, 0); err != nil {
		t.Errorf("default refused a shard at %.3f; it should only measure: %v", share, err)
	}
	if err := checkSelfplayPassCollapse(share, rows, 0.05); err == nil {
		t.Error("explicit bar failed to refuse a 90% pass shard")
	}
}

// Passing is correct play in a finished position, so averaging the whole game
// mixes the pathology with the endgame. Only opening, full-search rows count:
// fast-search rows are not policy targets at all.
func TestPassShareIgnoresEndgameAndFastRows(t *testing.T) {
	samples := []Sample{
		sampleWithPass(0, true, 0.02),                        // counted
		sampleWithPass(passShareOpeningPlies+30, true, 0.95), // endgame: not counted
		sampleWithPass(1, false, 0.95),                       // fast search: not a policy target
	}
	share, rows := openingPassShare(samples)
	if rows != 1 {
		t.Fatalf("counted %d rows, want only the opening full-search one", rows)
	}
	if share > 0.05 {
		t.Errorf("endgame or fast rows leaked into the share: got %.3f", share)
	}
}

// No opening full-search rows means the shard cannot be judged; that must read
// as "no opinion", not as a pass.
func TestPassShareWithNoOpeningRowsIsNotAFailure(t *testing.T) {
	share, rows := openingPassShare([]Sample{sampleWithPass(0, false, 0.9)})
	if rows != 0 {
		t.Fatalf("counted %d rows, want 0", rows)
	}
	if err := checkSelfplayPassCollapse(share, rows, 0.05); err != nil {
		t.Errorf("no rows should not fail: %v", err)
	}
}
